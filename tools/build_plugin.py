#!/usr/bin/env python3
"""Assemble the TKSfw plugin (one directory, two manifests) from the template and package it.

Source of truth                     ->  Build output
  VERSION                               version injected into both manifests
  template/.agents/skills/<name>/       plugins/tksfw/skills/<name>/      (tests/ and caches dropped)
  template/.agents/hooks/*.py           plugins/tksfw/hooks/*.py          (sync_harness.py dropped:
                                                                           it only serves the in-project layout)
  template/.agents/hooks/hooks.json     plugins/tksfw/hooks/hooks.json    commands rewritten from
                                        `python3 .agents/hooks/X.py` to
                                        `python3 "${CLAUDE_PLUGIN_ROOT}/hooks/X.py"`
  plugin/.codex-plugin/plugin.json      plugins/tksfw/.codex-plugin/plugin.json
  plugin/.claude-plugin/plugin.json     plugins/tksfw/.claude-plugin/plugin.json
  plugin/README.md                      plugins/tksfw/README.md

Why ${CLAUDE_PLUGIN_ROOT} in a shared hooks.json: Claude Code exports it to hook processes, and
Codex sets both PLUGIN_ROOT and (for compatibility) CLAUDE_PLUGIN_ROOT, so one file serves both.

Packages written to dist/ (all reproducible from the repo):
  tksfw-plugin-<v>.zip        the plugin directory alone (top-level folder `tksfw/`)
  tksfw-marketplace-<v>.zip   a self-contained marketplace root: both catalogs + plugins/tksfw/
  tksfw-template-<v>.zip      the per-project method instance (template/) + tools/new_project.py
A SHA256SUMS file accompanies the ZIPs (Claude Code `archive` sources can pin `sha256`).

Usage:  python3 tools/build_plugin.py [--no-zip] [--check]
  --check   build into a temp dir and compare with plugins/tksfw/ (exit 1 on drift) — for CI/tests
"""
import sys
sys.dont_write_bytecode = True
import os
import re
import json
import shutil
import hashlib
import zipfile
import tempfile
import argparse
import filecmp

REPO = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
TEMPLATE = os.path.join(REPO, "template")
PLUGIN_SRC = os.path.join(REPO, "plugin")
PLUGIN_OUT = os.path.join(REPO, "plugins", "tksfw")
DIST = os.path.join(REPO, "dist")
NAME = "tksfw"
IGNORE = shutil.ignore_patterns("__pycache__", ".DS_Store", "._*", ".mirror.json", "*.pyc")
SKILL_DROP_DIRS = {"tests"}
HOOK_DROP_FILES = {"sync_harness.py"}
HOOK_CMD = re.compile(r"python3 \.agents/hooks/([A-Za-z0-9_]+\.py)")


def version():
    with open(os.path.join(REPO, "VERSION"), encoding="utf-8") as fh:
        v = fh.read().strip()
    if not re.fullmatch(r"\d+\.\d+\.\d+([-+][0-9A-Za-z.-]+)?", v):
        sys.exit(f"VERSION must be semver, got {v!r}")
    return v


def copy_skills(out):
    src = os.path.join(TEMPLATE, ".agents", "skills")
    dst = os.path.join(out, "skills")
    os.makedirs(dst)
    names = []
    for name in sorted(os.listdir(src)):
        sdir = os.path.join(src, name)
        if not os.path.isfile(os.path.join(sdir, "SKILL.md")):
            continue
        shutil.copytree(sdir, os.path.join(dst, name), ignore=IGNORE)
        for d in SKILL_DROP_DIRS:
            shutil.rmtree(os.path.join(dst, name, d), ignore_errors=True)
        names.append(name)
    return names


def copy_hooks(out):
    src = os.path.join(TEMPLATE, ".agents", "hooks")
    dst = os.path.join(out, "hooks")
    os.makedirs(dst)
    for f in sorted(os.listdir(src)):
        if f.endswith(".py") and f not in HOOK_DROP_FILES:
            shutil.copy2(os.path.join(src, f), os.path.join(dst, f))
    with open(os.path.join(src, "hooks.json"), encoding="utf-8") as fh:
        cfg = json.load(fh)
    cfg["description"] = ("TKSfw plugin hooks — GENERATED by tools/build_plugin.py from "
                          "template/.agents/hooks/hooks.json; edit the template, then rebuild. "
                          "Scripts resolve the project root from $CLAUDE_PROJECT_DIR or by walking up "
                          "from the current directory to AGENTS.md; runtime state stays in the project's "
                          ".agents/workarea/.hook-state/, never in the plugin directory.")
    rewritten = 0
    for event, groups in cfg["hooks"].items():
        for g in groups:
            for h in g.get("hooks", []):
                new, n = HOOK_CMD.subn(r'python3 "${CLAUDE_PLUGIN_ROOT}/hooks/\1"', h["command"])
                if n == 0:
                    sys.exit(f"hooks.json: cannot rewrite command {h['command']!r} ({event})")
                h["command"] = new
                rewritten += n
    with open(os.path.join(dst, "hooks.json"), "w", encoding="utf-8") as fh:
        json.dump(cfg, fh, indent=2, ensure_ascii=False)
        fh.write("\n")
    return rewritten


def write_manifests(out, ver):
    for sub in (".codex-plugin", ".claude-plugin"):
        os.makedirs(os.path.join(out, sub))
        with open(os.path.join(PLUGIN_SRC, sub, "plugin.json"), encoding="utf-8") as fh:
            m = json.load(fh)
        m["version"] = ver
        if m.get("name") != NAME:
            sys.exit(f"{sub}/plugin.json: name must be {NAME!r}")
        for key in ("skills", "hooks"):
            v = m.get(key)
            if isinstance(v, str) and not v.startswith("./"):
                sys.exit(f"{sub}/plugin.json: {key} must be a ./-relative path")
        with open(os.path.join(out, sub, "plugin.json"), "w", encoding="utf-8") as fh:
            json.dump(m, fh, indent=2, ensure_ascii=False)
            fh.write("\n")
    readme = os.path.join(PLUGIN_SRC, "README.md")
    if os.path.isfile(readme):
        shutil.copy2(readme, os.path.join(out, "README.md"))


def build(out, ver):
    if os.path.exists(out):
        shutil.rmtree(out)
    os.makedirs(out)
    skills = copy_skills(out)
    n = copy_hooks(out)
    write_manifests(out, ver)
    # sanity: every hook script referenced exists in the bundle
    with open(os.path.join(out, "hooks", "hooks.json"), encoding="utf-8") as fh:
        cfg = json.load(fh)
    for groups in cfg["hooks"].values():
        for g in groups:
            for h in g["hooks"]:
                script = re.search(r'/hooks/([A-Za-z0-9_]+\.py)"', h["command"]).group(1)
                if not os.path.isfile(os.path.join(out, "hooks", script)):
                    sys.exit(f"bundle is missing hook script {script}")
    return skills, n


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def zip_dir(zpath, pairs):
    """pairs: [(abs_src_dir_or_file, arcname_prefix)]"""
    if os.path.exists(zpath):
        os.remove(zpath)
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for src, prefix in pairs:
            if os.path.isfile(src):
                z.write(src, os.path.join(prefix, os.path.basename(src)))
                continue
            for dirpath, dirnames, filenames in os.walk(src):
                dirnames[:] = sorted(d for d in dirnames if d not in ("__pycache__", ".hook-state"))
                for f in sorted(filenames):
                    if f in (".DS_Store", "STATE.md") or f.startswith("._") or f.endswith(".pyc"):
                        continue
                    ap = os.path.join(dirpath, f)
                    z.write(ap, os.path.join(prefix, os.path.relpath(ap, src)))


def package(ver):
    os.makedirs(DIST, exist_ok=True)
    made = []
    p = os.path.join(DIST, f"{NAME}-plugin-{ver}.zip")
    zip_dir(p, [(PLUGIN_OUT, NAME)])
    made.append(p)
    p = os.path.join(DIST, f"{NAME}-marketplace-{ver}.zip")
    zip_dir(p, [(os.path.join(REPO, ".claude-plugin"), f"{NAME}-marketplace/.claude-plugin"),
                (os.path.join(REPO, ".agents", "plugins"), f"{NAME}-marketplace/.agents/plugins"),
                (PLUGIN_OUT, f"{NAME}-marketplace/plugins/{NAME}"),
                (os.path.join(REPO, "docs", "distribution.md"), f"{NAME}-marketplace")])
    made.append(p)
    p = os.path.join(DIST, f"{NAME}-template-{ver}.zip")
    zip_dir(p, [(TEMPLATE, f"{NAME}-template/template"),
                (os.path.join(REPO, "tools", "new_project.py"), f"{NAME}-template/tools"),
                (os.path.join(REPO, "VERSION"), f"{NAME}-template")])
    made.append(p)
    with open(os.path.join(DIST, "SHA256SUMS"), "w", encoding="utf-8") as fh:
        for m in made:
            fh.write(f"{sha256(m)}  {os.path.basename(m)}\n")
    return made


def tree_equal(a, b):
    cmp = filecmp.dircmp(a, b, ignore=["__pycache__", ".DS_Store"])
    if cmp.left_only or cmp.right_only or cmp.diff_files or cmp.funny_files:
        return False
    return all(tree_equal(os.path.join(a, d), os.path.join(b, d)) for d in cmp.common_dirs)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--no-zip", action="store_true", help="assemble plugins/tksfw only")
    ap.add_argument("--check", action="store_true", help="verify plugins/tksfw is up to date")
    a = ap.parse_args()
    ver = version()
    if a.check:
        with tempfile.TemporaryDirectory() as tmp:
            out = os.path.join(tmp, NAME)
            build(out, ver)
            ok = os.path.isdir(PLUGIN_OUT) and tree_equal(out, PLUGIN_OUT)
        print("plugins/tksfw is up to date" if ok else "plugins/tksfw is STALE — run tools/build_plugin.py")
        sys.exit(0 if ok else 1)
    skills, n = build(PLUGIN_OUT, ver)
    print(f"built {os.path.relpath(PLUGIN_OUT, REPO)}  v{ver}  skills={skills}  hook commands rewritten={n}")
    if not a.no_zip:
        for m in package(ver):
            print(f"  {os.path.relpath(m, REPO)}  {sha256(m)[:12]}…")
        print(f"  dist/SHA256SUMS")


if __name__ == "__main__":
    main()
